#!/usr/bin/env node
/**
 * Self-host the designer fonts: downloads the latin woff2 files from Google
 * Fonts into public/fonts and writes src/app/fonts.css with @font-face rules.
 *
 *   npm run fonts:fetch
 */
import fs from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const OUT_DIR = path.join(ROOT, "public", "fonts");
const CSS_FILE = path.join(ROOT, "src", "app", "fonts.css");

const FAMILIES = [
  ["Lobster", [400]],
  ["Pacifico", [400]],
  ["Bebas Neue", [400]],
  ["Oswald", [400, 700]],
  ["Anton", [400]],
  ["Playfair Display", [400, 700]],
  ["Dancing Script", [400]],
  ["Montserrat", [400, 700]],
  ["Permanent Marker", [400]],
  ["Abril Fatface", [400]],
];

// a modern UA makes Google serve woff2 with unicode-range subsets
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";

await fs.mkdir(OUT_DIR, { recursive: true });
let css = "/* generated by scripts/fetch-fonts.mjs — self-hosted designer fonts */\n";

for (const [family, weights] of FAMILIES) {
  const q = `family=${family.replace(/ /g, "+")}${weights.length > 1 ? `:wght@${weights.join(";")}` : ""}`;
  const r = await fetch(`https://fonts.googleapis.com/css2?${q}&display=swap`, { headers: { "User-Agent": UA } });
  const text = await r.text();
  const blocks = text.match(/\/\*\s*latin\s*\*\/\s*@font-face\s*{[^}]+}/g) ?? [];
  if (!blocks.length) {
    console.warn(`! no latin block for ${family}`);
    continue;
  }
  for (const block of blocks) {
    const url = block.match(/url\((https:[^)]+\.woff2)\)/)?.[1];
    const weight = block.match(/font-weight:\s*(\d+)/)?.[1] ?? "400";
    if (!url) continue;
    const file = `${family.replace(/ /g, "-").toLowerCase()}-${weight}.woff2`;
    const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
    await fs.writeFile(path.join(OUT_DIR, file), buf);
    css += `@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:swap;src:url("/fonts/${file}") format("woff2");}\n`;
    console.log(`${family} ${weight} → public/fonts/${file} (${Math.round(buf.length / 1024)} KB)`);
  }
}

await fs.writeFile(CSS_FILE, css);
console.log(`\nwrote ${path.relative(ROOT, CSS_FILE)}`);
