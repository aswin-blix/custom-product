#!/usr/bin/env node
/**
 * Regenerate src/lib/printful/snapshot.generated.ts: static imports of the
 * offline catalog snapshot so it is bundled into serverless functions (Vercel)
 * instead of read from the filesystem at runtime.
 */
import fs from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const DATA = path.join(ROOT, "data", "printful");
const OUT = path.join(ROOT, "src", "lib", "printful", "snapshot.generated.ts");

const ids = (await fs.readdir(DATA)).filter((d) => /^\d+$/.test(d)).sort((a, b) => Number(a) - Number(b));
let src = "// GENERATED by scripts/gen-snapshot-index.mjs — do not edit.\n// Static imports keep the offline catalog snapshot inside the server bundle.\n";
for (const id of ids) {
  for (const f of ["product", "printfiles", "templates", "styles"]) src += `import p${id}_${f} from "../../../data/printful/${id}/${f}.json";\n`;
}
src += "\nexport const SNAPSHOTS: Record<number, { product: unknown; printfiles: unknown; templates: unknown; styles: unknown }> = {\n";
for (const id of ids) src += `  ${id}: { product: p${id}_product, printfiles: p${id}_printfiles, templates: p${id}_templates, styles: p${id}_styles },\n`;
src += "};\n";
await fs.writeFile(OUT, src);
console.log(`wrote ${path.relative(ROOT, OUT)} (${ids.length} products)`);
